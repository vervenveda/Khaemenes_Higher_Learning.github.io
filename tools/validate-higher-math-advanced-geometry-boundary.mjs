import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const root=path.resolve(process.cwd());
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const matrix=JSON.parse(read("courses/mathematics-execution-matrix-v1.json"));
const topo=matrix.courses.find(x=>x.id==="topology-differential-geometry");
const agt=matrix.courses.find(x=>x.id==="advanced-geometric-topology");
assert(topo&&agt,"advanced geometry courses missing");
assert.equal(topo.assessment_key,"khaemenes-topology-differential-geometry-assessment-v2");
assert.equal(topo.legacy_assessment_key,"khaemenes-topology-differential-geometry-assessment-v1");
assert.equal(topo.proof_mastery_contract?.noncompensatory,true);
assert.equal(topo.authority?.proof_review?.status,"required-evaluator-review");
assert.equal(topo.return_record?.exporter,"courses/shared/higher-math-evidence-receipt-v1.js");
const topoEngine=read("courses/topology-differential-geometry/assets/assessment-engine.js");
assert(topoEngine.includes("learnerId:LEARNER"));
assert(topoEngine.includes("proofReviewSatisfied:false"));
assert(topoEngine.includes("practicePassed:score>=80"));
const topoApp=read("courses/topology-differential-geometry/assets/app-core.js");
assert(topoApp.includes("topology-differential-geometry"));
assert(topoApp.includes("weighted average never substitutes"));
assert(topoApp.includes("data-higher-math-evidence-receipt"));

const manifest=JSON.parse(read("courses/advanced-geometric-topology/hybrid-runtime-contract-v1.json"));
assert.equal(manifest.architecture,"hybrid-legacy-v2");
assert.equal(manifest.curriculum.weeks,36);
assert.equal(manifest.curriculum.sessions,180);
assert.deepEqual(manifest.curriculum.migrated_rich_modules,["W01D1"]);
assert.equal(manifest.release_boundary.current_v2_rich_session_count,1);
assert.equal(manifest.release_boundary.current_legacy_fallback_session_count,179);
assert.equal(manifest.release_boundary.full_v2_migration,false);
assert.match(manifest.curriculum.retirement_rule,/Do not archive or remove course-data\.js/);
assert.equal(manifest.assessment.objective_threshold_percent,80);
assert.equal(manifest.assessment.proof_review,"required");
assert.equal(manifest.persistence.current_key,"khaemenes-hl-agtgmp-progress-v2");
assert.equal(manifest.persistence.legacy_key,"khaemenes-hl-agtgmp-progress-v1");
assert.equal(manifest.persistence.proof_evidence_from_legacy,"submitted-unreviewed");

assert.equal(agt.architecture,"hybrid-legacy-v2");
assert.equal(agt.migration?.rich_v2_sessions,1);
assert.equal(agt.migration?.legacy_fallback_sessions,179);
assert.deepEqual(agt.progression?.prerequisite_courses,["topology-differential-geometry"]);
assert.equal(agt.proof_mastery_contract?.noncompensatory,true);
assert.equal(agt.authority?.completion?.status,"multi-stream-noncompensatory");

const lessonEngine=read("courses/advanced-geometric-topology/assets/js/lesson-engine.js");
assert(lessonEngine.includes("Lesson content migration pending"));
assert(lessonEngine.includes("Mastery remains multi-stream"));
const mastery=read("courses/advanced-geometric-topology/assets/js/mastery-engine.js");
for(const term of ["record.mastery.conceptual","record.mastery.proof","record.mastery.lab","record.mastery.correction","record.mastery.defense"])assert(mastery.includes(term),term+" missing");
const identity=read("courses/advanced-geometric-topology/assets/identity-scope.js");
assert(identity.includes("learnerScopedStorage:true"));
assert(identity.includes("legacyKeysPreserved:true"));
console.log("PASS advanced geometry boundary: mature topology v2 contract, AGT 1-rich/179-fallback hybrid manifest, learner scope, and noncompensatory multi-stream mastery.");
