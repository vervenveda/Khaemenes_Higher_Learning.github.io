import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const root=path.resolve(process.cwd());
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const matrix=JSON.parse(read("courses/mathematics-execution-matrix-v1.json"));
const ids=["introduction-to-proofs","abstract-algebra","real-complex-analysis"];
for(const id of ids){
 const c=matrix.courses.find(x=>x.id===id);
 assert(c,id+" missing from matrix");
 assert.equal(c.assessment_scope,"local-course-learner",id+" assessment scope");
 assert.match(c.assessment_key,/assessment.*v2$/,id+" v2 assessment key");
 assert.match(c.legacy_assessment_key,/assessment.*v1$/,id+" legacy key");
 assert.equal(c.proof_mastery_contract?.required,true,id+" proof mastery required");
 assert.equal(c.proof_mastery_contract?.threshold_percent,80,id+" proof threshold");
 assert.equal(c.proof_mastery_contract?.objective_practice_authority,"formative-only",id+" objective practice authority");
 assert.equal(c.proof_mastery_contract?.written_proof_review,"required-evaluator-review",id+" written proof review");
 assert.equal(c.proof_mastery_contract?.noncompensatory,true,id+" proof review must be noncompensatory");
 assert.equal(c.authority?.proof_review?.status,"required-evaluator-review",id+" proof authority status");
 const map=JSON.parse(read(c.source)).course;
 assert.deepEqual(map.proof_mastery_contract,c.proof_mastery_contract,id+" map/matrix proof contract mismatch");
 const engine=read(c.root+"assets/assessment-engine.js");
 assert(engine.includes("HISTORY_PREFIX=\""+c.assessment_key+"\""),id+" v2 engine prefix missing");
 assert(engine.includes("LEGACY_KEY=\""+c.legacy_assessment_key+"\""),id+" legacy preservation missing");
 assert(engine.includes("proofReviewSatisfied:false"),id+" formative attempts must not certify proof review");
 assert(engine.includes("practicePassed:score>=80"),id+" 80% metadata missing");
 const app=read(c.root+"assets/app-core.js");
 assert(app.includes("written proof")||app.includes("written-proof"),id+" learner-facing proof requirement missing");
 assert(app.includes("weighted average never substitutes"),id+" noncompensatory gradebook notice missing");
 assert(app.includes("data-higher-math-evidence-receipt"),id+" evidence receipt control missing");
 const consoleHtml=read(c.root+"course-console.html");
 assert(consoleHtml.includes("higher-math-evidence-receipt-v1.js"),id+" course-records console missing shared receipt exporter");
}
const intro=matrix.courses.find(x=>x.id==="introduction-to-proofs").progression;
assert(intro.recommended_next.includes("abstract-algebra")&&intro.recommended_next.includes("real-complex-analysis"));
const aa=matrix.courses.find(x=>x.id==="abstract-algebra").progression;
assert.deepEqual(aa.prerequisite_courses,["introduction-to-proofs"]);
const ra=matrix.courses.find(x=>x.id==="real-complex-analysis").progression;
assert.deepEqual(ra.prerequisite_courses,["introduction-to-proofs"]);
const receipt=read("courses/shared/higher-math-evidence-receipt-v1.js");
for(const id of ids)assert(receipt.includes('"'+id+'":{'),id+" receipt config missing");
assert(receipt.includes('proofReviewStatus:cfg.proofReviewRequired===true?"requires-evaluator-review":"not-applicable"'));
console.log("PASS proof sequence: learner-scoped assessments, 80% formative threshold, noncompensatory written-proof review, evidence receipts, progression graph.");
